// Generates schema/brain.schema.json and src/generated.ts from the Rust receipt (fettle-receipt's
// `receipt-schema` bin), so the receipt's types have exactly one hand-written definition: the Rust structs.
// Run `npm run gen:brain-types` after changing them; test/types.test.ts fails until you do.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { delimiter, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { jsonSchemaToZod } from "json-schema-to-zod";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const repoRoot = here("../../../");
const HEADER =
  "// Generated by packages/brain/scripts/gen-types.mjs from crates/fettle-receipt and fettle-verdicts.\n" +
  "// Don't edit by hand: change the Rust structs and run `npm run gen:brain-types`.\n\n";

function schemaFromRust() {
  // rustup's bin folder isn't always on PATH for Node.
  const env = { ...process.env, PATH: `${join(homedir(), ".cargo", "bin")}${delimiter}${process.env.PATH}` };
  const args = ["run", "-q", "-p", "fettle-receipt", "--features", "schema", "--bin", "receipt-schema"];
  return execFileSync("cargo", args, { cwd: repoRoot, env, encoding: "utf8" });
}

/**
 * Prepares the Rust schema for zod and for the React code's types:
 * - drops every `default`: json-schema-to-zod treats such a field as required; Rust's are optional.
 * - drops `null`: every `Option` in these structs is skipped when empty, so Rust never writes null.
 *   An optional field is then `string | undefined`, as the drawing code expects (test/types.test.ts
 *   checks every golden still fits).
 */
function prepare(node) {
  if (Array.isArray(node)) return node.map(prepare);
  if (!node || typeof node !== "object") return node;
  const out = Object.fromEntries(Object.entries(node).filter(([k]) => k !== "default").map(([k, v]) => [k, prepare(v)]));
  if (Array.isArray(out.type)) {
    const types = out.type.filter((t) => t !== "null");
    out.type = types.length === 1 ? types[0] : types;
  }
  if (Array.isArray(out.anyOf)) {
    const options = out.anyOf.filter((o) => o.type !== "null");
    if (options.length === 1) {
      delete out.anyOf;
      Object.assign(out, options[0]);
    } else out.anyOf = options;
  }
  return out;
}

export function generate() {
  const schemaJson = schemaFromRust();
  const both = prepare(JSON.parse(schemaJson));
  const receipt = jsonSchemaToZod(both.Receipt, { name: "ReceiptSchema", module: "esm" });
  // The second schema shares the first one's `import { z }`.
  const model = jsonSchemaToZod(both.ReceiptModel, { name: "ReceiptModelSchema", module: "esm" }).replace(/^import \{ z \} from "zod"\n+/, "");
  return { schemaJson, code: `${HEADER}${receipt}\n\n${model}\n` };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { schemaJson, code } = generate();
  writeFileSync(here("../schema/brain.schema.json"), schemaJson);
  writeFileSync(here("../src/generated.ts"), code);
  console.log("wrote schema/brain.schema.json and src/generated.ts");
}
