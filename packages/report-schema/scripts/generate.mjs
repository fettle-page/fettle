// Generates schema/report.schema.json and src/generated.ts from the Rust facts crate,
// so the report format has exactly one hand-written definition (crates/fettle-facts).
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { jsonSchemaToZod } from "json-schema-to-zod";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const repoRoot = here("../../../");
const HEADER = "// Generated by packages/report-schema/scripts/generate.mjs from crates/fettle-facts.\n// Don't edit by hand: change the Rust structs and run `npm run gen:schema`.\n\n";

function schemaFromRust() {
  // rustup's bin folder isn't always on PATH for Node.
  const env = { ...process.env, PATH: `${join(homedir(), ".cargo", "bin")};${process.env.PATH}` };
  return execFileSync("cargo", ["run", "-q", "-p", "fettle-facts", "--bin", "schema"], { cwd: repoRoot, env, encoding: "utf8" });
}

// Uploaded reports are untrusted, so every string and list gets a ceiling. Real reports are
// far below these; the limits only stop abuse (the Worker also caps uploads at 256 KB).
const MAX_STRING = 512;
const MAX_ITEMS = 256;

const hasType = (node, t) => node.type === t || (Array.isArray(node.type) && node.type.includes(t));

/**
 * Prepares the Rust schema for zod:
 * - drops every `default`: json-schema-to-zod ignores nested defaults but then treats the field
 *   as required, while Rust accepts it missing (`#[serde(default)]`). Optional fields stay optional.
 * - adds `maxLength` / `maxItems` limits for untrusted input.
 */
function prepare(node) {
  if (Array.isArray(node)) return node.map(prepare);
  if (!node || typeof node !== "object") return node;
  const out = Object.fromEntries(Object.entries(node).filter(([k]) => k !== "default").map(([k, v]) => [k, prepare(v)]));
  if (hasType(out, "string") && out.maxLength === undefined) out.maxLength = MAX_STRING;
  if (hasType(out, "array") && out.maxItems === undefined) out.maxItems = MAX_ITEMS;
  return out;
}

export function generate() {
  const schemaJson = schemaFromRust();
  const schema = prepare(JSON.parse(schemaJson));
  const code = HEADER + jsonSchemaToZod(schema, { name: "ReportSchema", module: "esm" }) + "\n";
  return { schemaJson, code };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { schemaJson, code } = generate();
  writeFileSync(here("../schema/report.schema.json"), schemaJson);
  writeFileSync(here("../src/generated.ts"), code);
  console.log("wrote schema/report.schema.json and src/generated.ts");
}
